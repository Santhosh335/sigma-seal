"""
Days 1-2: batch proving + timing benchmarks.

Reuses the circuit/keys already generated by generate_proof.py (model.compiled,
proving.key, verifying.key, settings.json must already exist -- run
generate_proof.py once first if they don't).

For each of N sample events, generates a witness + proof + verifies it,
and records timing and proof size -- the real numbers anyone evaluating
this project will ask about first.
"""
import json
import os
import time

import ezkl
import numpy as np
import pandas as pd

from data_loader import build_model_inputs, load_features


def main(h5_path: str, n_samples: int = 10):
    compiled_path = "model.compiled"
    pk_path = "proving.key"
    vk_path = "verifying.key"
    settings_path = "settings.json"

    print(f"Loading {n_samples} sample background events from {h5_path} ...")
    raw = load_features(h5_path)
    feats = build_model_inputs(raw)
    background = feats[feats["label"] == 0].drop(columns="label").values

    mean = np.load("scaler_mean.npy")
    scale = np.load("scaler_scale.npy")
    samples = (background[:n_samples] - mean) / scale

    results = []
    for i, sample in enumerate(samples):
        input_path = f"batch_input_{i}.json"
        witness_path = f"batch_witness_{i}.json"
        proof_path = f"batch_proof_{i}.pf"

        json.dump({"input_data": [sample.astype(np.float32).tolist()]}, open(input_path, "w"))

        t0 = time.time()
        ezkl.gen_witness(input_path, compiled_path, witness_path)
        t1 = time.time()
        ezkl.prove(witness_path, compiled_path, pk_path, proof_path)
        t2 = time.time()
        verified = ezkl.verify(proof_path, settings_path, vk_path)
        t3 = time.time()

        proof_size_kb = os.path.getsize(proof_path) / 1024

        results.append({
            "event": i,
            "witness_gen_s": round(t1 - t0, 3),
            "prove_s": round(t2 - t1, 3),
            "verify_s": round(t3 - t2, 3),
            "proof_size_kb": round(proof_size_kb, 1),
            "verified": verified,
        })
        print(f"Event {i}: witness={t1-t0:.2f}s prove={t2-t1:.2f}s "
              f"verify={t3-t2:.2f}s proof={proof_size_kb:.1f}KB verified={verified}")

    df = pd.DataFrame(results)
    df.to_csv("batch_benchmark_results.csv", index=False)
    print("\n=== Summary across all events ===")
    print(df[["witness_gen_s", "prove_s", "verify_s", "proof_size_kb"]].describe())
    print(f"\nAll verified: {df['verified'].all()}")
    print("Saved full results to batch_benchmark_results.csv")


if __name__ == "__main__":
    import sys
    h5_path = sys.argv[1] if len(sys.argv) > 1 else "events_anomalydetection_v2.features.h5"
    n = int(sys.argv[2]) if len(sys.argv) > 2 else 10
    main(h5_path, n)